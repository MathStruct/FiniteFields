# The roots α_n of the Conway polynomials C_n in GF(2^n) ⊂ On_2 (backlog J10, `embed` between
# the rank-encoded fields and the Conway fields), written to
# julia/FiniteFieldArithmetic.jl/src/nim_conway_roots.jl.
#
# Rule (extends the nimber ↔ Conway convention of polyfield.md, which it reproduces for n = 2^k):
# for every n in Lübeck's table, in increasing order, α_n is the root r of C_n in GF(2^n) ⊂ On_2
# that is compatible with every α_m already chosen for m | n, m < n,
#     r^((2^n - 1)/(2^m - 1)) = α_m        (the compatibility of Conway polynomials),
# and has the least rank (= the least ordinal) among those. Every divisor of a table degree is a
# table degree (the missing degrees 93 … 128 have no multiple ≤ 128). Writing the roots as
# r^(2^i), i mod n, compatibility with α_m fixes i mod m; the conditions for the m | n agree on
# gcds (the α_m are compatible among themselves), so by the Chinese remainder theorem the
# compatible roots are the i in one class mod L = lcm{m | n, m < n}: n / L of them (the script
# checks that there is at least one and prints the count).
#
# Run: nix develop .#julia -c julia --project=julia/FiniteFieldArithmetic.jl research/nimber_closure/conway_roots.jl

using FiniteFieldArithmetic
using FiniteFieldArithmetic: unsafe_frombits, bits, max_bits, conway_exponent
using Random

# A root of the polynomial with coefficient vector f (lowest first, monic, over F, splitting into
# distinct linear factors): Cantor–Zassenhaus with the trace Tr(βX) mod g.
function find_root_generic(::Type{F}, f::Vector{F}, rng) where {F}
    n = degree(F)
    trim!(p) = (while !isempty(p) && iszero(p[end]); pop!(p); end; p)
    monic(p) = (c = inv(p[end]); [x * c for x in p])
    function pmod(a, g)
        a = trim!(copy(a)); dg = length(g) - 1
        for i in length(a):-1:(dg + 1)
            c = a[i]; iszero(c) && continue
            for j in 0:dg
                a[i - dg + j] += c * g[j + 1]
            end
        end
        return trim!(a[1:min(end, dg)])
    end
    function pmul(a, b)
        (isempty(a) || isempty(b)) && return F[]
        c = zeros(F, length(a) + length(b) - 1)
        for i in eachindex(a), j in eachindex(b)
            c[i + j - 1] += a[i] * b[j]
        end
        return c
    end
    function pgcd(a, b)
        a, b = trim!(copy(a)), trim!(copy(b))
        while !isempty(b)
            b = monic(b); a, b = b, pmod(a, b)
        end
        return monic(a)
    end
    padd(a, b) = (length(a) < length(b) && ((a, b) = (b, a)); c = copy(a);
                  for i in eachindex(b); c[i] += b[i]; end; trim!(c))
    function pdiv(a, g)
        a = copy(a); dg = length(g) - 1
        q = zeros(F, length(a) - dg)
        for i in length(a):-1:(dg + 1)
            c = a[i]; q[i - dg] = c
            for j in 0:dg
                a[i - dg + j] += c * g[j + 1]
            end
        end
        return trim!(q)
    end
    g = monic(f)
    while length(g) > 2
        β = unsafe_frombits(F, rand(rng, UInt128) & UInt128(max_bits(F)) % storagetype(F))
        iszero(β) && continue
        y = pmod([zero(F), β], g)              # βX
        t = copy(y)
        for _ in 1:(n - 1)
            y = pmod(pmul(y, y), g)
            t = padd(t, y)
        end
        h = pgcd(g, t)
        (length(h) <= 1 || length(h) == length(g)) && continue
        q = pdiv(g, h)
        g = length(h) <= length(q) ? h : monic(q)
    end
    return g[1]                                 # X + r: r = -g[1] = g[1]
end

storagetype(::Type{F}) where {F} = FiniteFieldArithmetic.storagetype(F)

function compute_roots()
    rng = Xoshiro(20261121)
    α = Dict{Int, Any}()
    for n in conway_degrees()
        F = nim_field(n)
        if n == 1
            α[1] = one(F); continue
        end
        C = conway_field(n)
        low = UInt128(FiniteFieldArithmetic.field_modulus(C))
        f = [isodd(low >> i) ? one(F) : zero(F) for i in 0:(n - 1)]
        push!(f, one(F))
        r = find_root_generic(F, f, rng)
        orbit = [r]
        for _ in 2:n
            push!(orbit, orbit[end] * orbit[end])
        end
        @assert length(unique(bits.(orbit))) == n
        divs = [m for m in conway_degrees() if m < n && n % m == 0]
        good = filter(orbit) do s
            all(m -> s^conway_exponent(m, n) == embed(F, α[m]), divs)
        end
        isempty(good) && error("no compatible root of C_$n")
        α[n] = good[argmin(bits.(good))]
        println(stderr, "n = $n: $(length(good)) compatible roots, α = ", repr(bits(α[n])))
    end
    return α
end

α = compute_roots()
